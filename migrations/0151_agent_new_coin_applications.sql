CREATE TABLE agent_new_coin_applications (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    agent_id BIGINT UNSIGNED NOT NULL,
    agent_admin_id BIGINT UNSIGNED NOT NULL,
    symbol VARCHAR(32) NOT NULL,
    name VARCHAR(128) NOT NULL,
    precision_scale INT NOT NULL,
    total_supply DECIMAL(38,18) NOT NULL,
    issue_price DECIMAL(38,18) NOT NULL,
    quote_asset_id BIGINT UNSIGNED NOT NULL,
    quote_symbol VARCHAR(64) NOT NULL,
    listed_at DATETIME(3) NOT NULL,
    reason VARCHAR(500) NOT NULL,
    idempotency_key VARBINARY(128) NOT NULL,
    status VARCHAR(16) NOT NULL DEFAULT 'pending',
    project_id BIGINT UNSIGNED NULL,
    reviewed_by BIGINT UNSIGNED NULL,
    review_reason VARCHAR(500) NULL,
    created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    reviewed_at DATETIME(3) NULL,
    UNIQUE KEY uk_coin_application_intent (agent_admin_id, idempotency_key),
    UNIQUE KEY uk_coin_application_project (project_id),
    KEY idx_coin_application_owner (agent_admin_id, agent_id, status, id),
    KEY idx_coin_application_queue (status, id),
    FOREIGN KEY (agent_id) REFERENCES agents(id),
    FOREIGN KEY (agent_admin_id) REFERENCES agent_admin_users(id),
    FOREIGN KEY (quote_asset_id) REFERENCES assets(id),
    FOREIGN KEY (project_id) REFERENCES new_coin_projects(id),
    FOREIGN KEY (reviewed_by) REFERENCES admin_users(id),
    CHECK (precision_scale BETWEEN 0 AND 18),
    CHECK (total_supply > 0 AND issue_price > 0),
    CHECK ((status = 'pending' AND reviewed_by IS NULL AND review_reason IS NULL AND reviewed_at IS NULL AND project_id IS NULL)
        OR (status = 'rejected' AND reviewed_by IS NOT NULL AND review_reason IS NOT NULL AND reviewed_at IS NOT NULL AND project_id IS NULL)
        OR (status = 'approved' AND reviewed_by IS NOT NULL AND review_reason IS NOT NULL AND reviewed_at IS NOT NULL AND project_id IS NOT NULL))
) DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
